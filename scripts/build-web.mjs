// Generates the browser "card kit" used by the two static web pages:
//   preview/generated/   — for preview/preview_gallery.html (animated flip gallery)
//   editor/generated/    — for editor/index.html (question editor)
// Each generated/ folder is self-contained (no paths outside its app folder), so preview/ or editor/
// can be copied to a web server or opened by double-click (file://). Contents:
//   card-kit.js    the SAME render code as the PDFs (src/icons.mjs + src/templates.mjs), the shared
//                  content rules (src/rules.mjs) and exports (src/data-io.mjs), bundled as a classic script
//   card-kit.css   fonts + design tokens + card styles + geometry from config/print-settings.json
//   autofit.js     copy of src/autofit.js (text fitting, identical to the print renders)
//   cards-data.js  copy of data/cards.json as window.CARDS_DATA
//   fonts/         the self-hosted OFL fonts and their licences
// After writing, the bundle is executed in a sandbox and every card is compared with the Node render.
import { readFileSync, writeFileSync, mkdirSync, rmSync, copyFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { createHash } from "node:crypto";
import vm from "node:vm";
import { ROOT, CARDS_FILE, loadProject, fontCoverage } from "./lib.mjs";
import { renderFront, renderBack, loadBacks, cssVars } from "../src/templates.mjs";
import { cardsToCsv, formatCardsJSON } from "../src/data-io.mjs";
import { cardTextIssues } from "../src/rules.mjs";

const { settings, data, gateMap } = loadProject();
const backs = loadBacks(ROOT, data.gates);
const APPS = ["preview", "editor"];
const MODULES = ["src/icons.mjs", "src/templates.mjs", "src/rules.mjs", "src/data-io.mjs"];

/** ES module → plain script body (drops imports, unwraps `export`). Fails loudly on forms it does not handle. */
function toClassic(rel) {
  let src = readFileSync(join(ROOT, rel), "utf8");
  src = src.replace(/^import\s[^;]+;[ \t]*$/gm, "");
  src = src.replace(/^export\s+(?=(?:async\s+)?function\b|const\b|let\b|class\b)/gm, "");
  if (/^\s*(?:import|export)\b/m.test(src)) throw new Error(`${rel}: unsupported import/export form for the browser bundle`);
  return `// ---- ${rel} ----\n${src.trim()}\n`;
}

const rawData = readFileSync(join(ROOT, CARDS_FILE), "utf8");
const sha256 = createHash("sha256").update(rawData).digest("hex");
const generated = new Date().toISOString();
const banner = (what) => `/* GENERATED by scripts/build-web.mjs (npm run build) on ${generated} — DO NOT EDIT.\n   ${what} */\n`;

const kitSettings = { card: settings.card, text_fit: settings.text_fit };
const gateInfo = data.gates.map(({ gate, short_en, short_fr, name_en, name_fr }) => ({ gate, short_en, short_fr, name_en, name_fr }));

const kitJs = `${banner("Edit src/*.mjs, config/print-settings.json or assets/backs/*.svg instead, then rebuild.")}(function () {
"use strict";
${MODULES.map(toClassic).join("\n")}
// ---- build data ----
const KIT_SETTINGS = ${JSON.stringify(kitSettings)};
const KIT_BACKS = ${JSON.stringify(backs)};
window.__FIT__ = KIT_SETTINGS.text_fit;
window.CardKit = {
  built: ${JSON.stringify(generated)},
  settings: KIT_SETTINGS,
  geometry: cardGeometry(KIT_SETTINGS),
  gates: ${JSON.stringify(gateInfo)},
  backs: KIT_BACKS,
  esc: esc,
  renderFront: renderFront,
  renderBack: function (gate) { return renderBack(gate, KIT_BACKS); },
  rules: { GATES: GATES, ANSWER_GATES: ANSWER_GATES, PER_GATE: PER_GATE, LENGTH_LIMITS: LENGTH_LIMITS, mcOptions: mcOptions, answerLetter: answerLetter, cardTextIssues: cardTextIssues, nearDuplicates: nearDuplicates },
  io: { formatCardsJSON: formatCardsJSON, cardsToCsv: cardsToCsv, csvCell: csvCell },
  fontCoverage: ${JSON.stringify(fontCoverage())}
};
})();
`;

// Short font file names: Windows browsers cannot open files whose full path exceeds 260 characters,
// and these folders may be copied deep inside OneDrive/SharePoint paths.
const shortFont = (f) => f.endsWith(".woff2")
  ? f.replace("atkinson-hyperlegible-", "ah-").replace("barlow-condensed-", "bc-").replace("latin-ext-", "x").replace("latin-", "").replace("-normal", "").replace("-italic", "i")
  : f;
const fontsCss = readFileSync(join(ROOT, "design/fonts.css"), "utf8").replace(/url\(\.\.\/assets\/fonts\/([^)]+)\)/g, (_, f) => `url(fonts/${shortFont(f)})`);
const kitCss = `${banner("Fonts, design tokens and card styles. Edit design/*.css, src/cards.css or config/print-settings.json instead.")}
${fontsCss}
${readFileSync(join(ROOT, "design/tokens.css"), "utf8")}
${readFileSync(join(ROOT, "src/cards.css"), "utf8")}
${cssVars(settings)}
`;

const dataJs = `${banner(`Copy of ${CARDS_FILE} (the single source of truth). Edit the cards with editor/index.html or in data/cards.json, then rebuild.`)}window.CARDS_DATA = ${rawData.trim()};
window.CARDS_DATA_INFO = ${JSON.stringify({ source: CARDS_FILE, generated, sha256 })};
`;

const readme = `GENERATED FILES — DO NOT EDIT

Everything in this folder is written by \`npm run build\` (scripts/build-web.mjs) from:
  data/cards.json            card text (single source of truth)
  src/*.mjs, src/cards.css   card templates, rules and styles (same code as the print PDFs)
  design/*.css, assets/      colours, fonts, card-back artwork
  config/print-settings.json card size and text-fit settings

Any change made here is overwritten by the next build.
Fonts: Atkinson Hyperlegible and Barlow Condensed, SIL Open Font License 1.1 (licences in fonts/).
`;

const fontFiles = readdirSync(join(ROOT, "assets/fonts"));
for (const app of APPS) {
  const dir = join(ROOT, app, "generated");
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(join(dir, "fonts"), { recursive: true });
  writeFileSync(join(dir, "card-kit.js"), kitJs, "utf8");
  writeFileSync(join(dir, "card-kit.css"), kitCss, "utf8");
  writeFileSync(join(dir, "autofit.js"), banner("Copy of src/autofit.js.") + readFileSync(join(ROOT, "src/autofit.js"), "utf8"), "utf8");
  writeFileSync(join(dir, "cards-data.js"), dataJs, "utf8");
  writeFileSync(join(dir, "README.txt"), readme, "utf8");
  for (const f of fontFiles) copyFileSync(join(ROOT, "assets/fonts", f), join(dir, "fonts", shortFont(f)));
}
const fontNames = fontFiles.map(shortFont);
if (new Set(fontNames).size !== fontFiles.length) throw new Error("Shortened font file names collide: " + fontNames.join(", "));
const missingFont = [...fontsCss.matchAll(/url\(fonts\/([^)]+)\)/g)].map((m) => m[1]).filter((f) => !fontNames.includes(f));
if (missingFont.length) throw new Error("card-kit.css refers to missing font files: " + missingFont.join(", "));

/* ---------------- Verify: the browser bundle renders exactly what the print pipeline renders ---------------- */
const sandbox = { window: {} };
vm.createContext(sandbox);
vm.runInContext(kitJs, sandbox, { filename: "card-kit.js" });
vm.runInContext(dataJs, sandbox, { filename: "cards-data.js" });
const kit = sandbox.window.CardKit;
const webData = sandbox.window.CARDS_DATA;
const mismatch = [];
for (const c of data.cards) if (kit.renderFront(c, gateMap[c.gate]) !== renderFront(c, gateMap[c.gate])) mismatch.push(`${c.id}/${c.card_type}`);
for (const g of data.gates) if (kit.renderBack(g.gate) !== renderBack(g.gate, backs)) mismatch.push(`back ${g.gate}`);
if (mismatch.length) throw new Error(`Browser card kit renders differently from the print templates: ${mismatch.join(", ")}`);
if (kit.io.cardsToCsv(webData) !== cardsToCsv(data)) throw new Error("Browser CSV export differs from data/cards.csv generation.");
if (kit.io.formatCardsJSON(webData) !== rawData.replace(/\r\n/g, "\n")) throw new Error(`Browser JSON export of unchanged data differs from ${CARDS_FILE} (formatting).`);
const q = (c) => (c.card_type === "answer" ? data.cards.find((x) => x.card_type === "question" && x.id === c.id) : undefined);
const issuesNode = JSON.stringify(data.cards.map((c) => cardTextIssues(c, { question: q(c) })));
const issuesWeb = JSON.stringify(webData.cards.map((c) => kit.rules.cardTextIssues(c, { question: c.card_type === "answer" ? webData.cards.find((x) => x.card_type === "question" && x.id === c.id) : undefined })));
if (issuesNode !== issuesWeb) throw new Error("Browser content rules disagree with scripts/validate.mjs rules.");
if (formatCardsJSON(data) !== rawData.replace(/\r\n/g, "\n")) console.warn(`⚠ ${CARDS_FILE} is not in canonical formatting (2-space JSON); editor exports will reformat it.`);

const kb = (s) => `${(Buffer.byteLength(s) / 1024).toFixed(0)} KB`;
console.log(`✓ preview/generated + editor/generated — card-kit.js ${kb(kitJs)}, card-kit.css ${kb(kitCss)}, cards-data.js ${kb(dataJs)}, ${fontFiles.length} font files`);
console.log(`✓ Browser kit verified: ${data.cards.length} fronts + ${data.gates.length} backs identical to the print templates; CSV/JSON exports and content rules identical`);
